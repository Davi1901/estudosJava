package fundamentos;

public class ConceitosMatematicos {
    public static void main(String[] args){

        double result;

        result = Math.pow(2, 3);
        result = Math.abs(-10);
        result = Math.sqrt(9);
        result = Math.round(5.2);
        result = Math.ceil(2.1);
        result = Math.floor(3.99);
        result = Math.max(30, 35);
        result = Math.min(1, 2);
        System.out.println(result);

    }
}
