package fundamentos;

public class Variaveis {
    public static void main(String[] args){
        // Criação de variáveis do tipo inteiro;

        int idade = 21;
        int ano = 2026;
        int quantidade = 1;

        //Criação de variáveis do tipo dobule(número com casas decimais)

        double preco = 29.90;
        double gpa = 3.5;
        double temp = -12.5;

        //Criação de variáveis do tipo char(No caso servem para colocar apenas um caracterer, lembrando que tem que ser usado aspas simples('');

        char grade = 'A';
        char simbolo = '!';
        char moeda = '$';

        //Criação de variáveis do tipo boolean(só tem valor false ou true)

        boolean isEstudante = true;
        boolean forVenda = false;
        boolean isOnline = true;

        //Criação de variáveis do tipo String

        String nome = "Davi";
        String comida = "Macarrão";
        String email = "davibitencourt1901@gmail.com";
        String serie = "Dexter";

        System.out.println("A minha comida favorita é: " + comida);

        System.out.println("Seu email é: " + email);

        System.out.println("Olá, " + nome);
        System.out.println("Você tem: " + ano + " anos");


    }
}
